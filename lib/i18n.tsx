const dictionaries: Record<Lang, Record<TKey, string>> = { sq, en };

export function translate(lang: Lang, key: TKey, params?: Record<string, string | number>) {
  let s = dictionaries[lang][key] ?? sq[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey, params?: Record<string, string | number>) => string;
  /** Pick the localized variant of a field, falling back to Albanian. */
  pick: (sqValue: string | null | undefined, enValue: string | null | undefined) => string;
};

const I18nContext = createContext<Ctx | null>(null);
const STORAGE_KEY = 'eko.lang';

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() =>
    getLocales()[0]?.languageCode === 'en' ? 'en' : 'sq',
  );

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY).then((v) => {
      if (v === 'sq' || v === 'en') setLangState(v);
    });
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    AsyncStorage.setItem(STORAGE_KEY, l).catch(() => {});
  }, []);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      setLang,
      t: (key, params) => translate(lang, key, params),
      pick: (a, b) => (lang === 'en' && b ? b : a || b || ''),
    }),
    [lang, setLang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const c = useContext(I18nContext);
  if (!c) throw new Error('useI18n outside provider');
  return c;
}

/** Turn a Supabase/RPC error into a translated message. */
export function errorText(t: Ctx['t'], err: unknown): string {
  const msg = String((err as any)?.message ?? err ?? '');
  const code = msg.match(/[A-Z][A-Z_]{3,}/)?.[0];
  if (code && (`e_${code}` as TKey) in sq) return t(`e_${code}` as TKey);
  if (/Invalid login credentials/i.test(msg)) return t('invalidCredentials');
  if (/Email not confirmed/i.test(msg)) return t('emailNotConfirmed');
  if (/Failed to fetch|Network request failed|NetworkError/i.test(msg)) return t('e_network');
  return msg || t('error');
}
