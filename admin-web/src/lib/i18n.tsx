export type Lang = 'sq' | 'en';
type Params = Record<string, string | number | null | undefined>;
type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey, p?: Params) => string; pick: (a?: string | null, b?: string | null) => string };

const I18n = createContext<Ctx | null>(null);
const KEY = 'eko-admin-lang';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return localStorage.getItem(KEY) === 'en' ? 'en' : 'sq';
    } catch {
      return 'sq';
    }
  });
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(KEY, l);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = l;
  }, []);
  const value = useMemo<Ctx>(() => {
    const dict = lang === 'en' ? en : sq;
    return {
      lang,
      setLang,
      t: (k, p) => {
        let s = dict[k] ?? sq[k] ?? k;
        if (p) for (const [n, v] of Object.entries(p)) s = s.split(`{${n}}`).join(String(v ?? ''));
        return s;
      },
      pick: (a, b) => (lang === 'en' && b ? b : a || b || ''),
    };
  }, [lang, setLang]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export function useI18n() {
  const c = useContext(I18n);
  if (!c) throw new Error('useI18n outside provider');
  return c;
}

/** Translate a Supabase / RPC error. */
export function errorText(t: Ctx['t'], err: unknown): string {
  const msg = String((err as any)?.message ?? err ?? '');
  const code = msg.match(/\b[A-Z][A-Z_]{3,}\b/)?.[0];
  if (code && `e_${code}` in sq) return t(`e_${code}` as TKey);
  if (/JWT|refresh token|not authenticated/i.test(msg)) return t('e_session');
  if (/Failed to fetch|NetworkError|Load failed/i.test(msg)) return t('e_network');
  return msg || t('error');
}
